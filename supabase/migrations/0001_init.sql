-- Baby Tracker schema. Run once in the Supabase SQL editor (or `supabase db push`).
--
-- A household is one baby's shared record. Each parent/carer signs in with their own account and
-- becomes a member by creating the household or joining with its invite code. Row level security
-- limits every read and write to members, so the publishable key in the web app exposes nothing.

create table public.households (
  id uuid primary key default gen_random_uuid(),
  baby_name text not null default '',
  birth_date date,
  invite_code text not null unique default upper(substr(md5(random()::text), 1, 8)),
  created_by uuid default auth.uid() references auth.users on delete set null,
  created_at timestamptz not null default now()
);

create table public.household_members (
  household_id uuid not null references public.households on delete cascade,
  user_id uuid not null references auth.users on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (household_id, user_id)
);

create index household_members_user_idx on public.household_members (user_id);

create table public.entries (
  -- Generated by the app so entries can show up before the server answers.
  id uuid primary key,
  household_id uuid not null references public.households on delete cascade,
  type text not null check (type in ('sleep', 'feed', 'diaper', 'pump', 'growth', 'health', 'activity', 'note')),
  start_at timestamptz not null,
  -- Null on a timed entry while its timer is running.
  end_at timestamptz check (end_at is null or end_at >= start_at),
  kind text,
  side text check (side in ('left', 'right', 'both')),
  amount_ml double precision check (amount_ml > 0),
  milk text check (milk in ('breast', 'formula')),
  food text,
  weight_kg double precision check (weight_kg > 0),
  height_cm double precision check (height_cm > 0),
  head_cm double precision check (head_cm > 0),
  temp_c double precision,
  medicine text,
  dose text,
  notes text,
  created_by uuid default auth.uid() references auth.users on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index entries_household_start_idx on public.entries (household_id, start_at desc);

create function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger entries_touch_updated_at before update on public.entries
for each row execute function public.touch_updated_at();

-- Membership check used by the policies. Security definer so it can read household_members
-- without recursing into that table's own policy.
create function public.is_household_member(target uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.household_members
    where household_id = target and user_id = (select auth.uid())
  );
$$;

alter table public.households enable row level security;
alter table public.household_members enable row level security;
alter table public.entries enable row level security;

create policy "Members read their household" on public.households
  for select to authenticated using (public.is_household_member(id));
create policy "Members update their household" on public.households
  for update to authenticated using (public.is_household_member(id)) with check (public.is_household_member(id));

create policy "Members see who else is in the household" on public.household_members
  for select to authenticated using (public.is_household_member(household_id));
create policy "Members can leave" on public.household_members
  for delete to authenticated using (user_id = (select auth.uid()));

create policy "Members read entries" on public.entries
  for select to authenticated using (public.is_household_member(household_id));
create policy "Members add entries" on public.entries
  for insert to authenticated with check (public.is_household_member(household_id));
create policy "Members edit entries" on public.entries
  for update to authenticated using (public.is_household_member(household_id)) with check (public.is_household_member(household_id));
create policy "Members delete entries" on public.entries
  for delete to authenticated using (public.is_household_member(household_id));

-- Creating and joining go through functions so the household row and the membership are written
-- together, and so nobody can list households to find invite codes.
create function public.create_household(baby_name text, birth_date date) returns public.households
language plpgsql security definer set search_path = '' as $$
declare
  created public.households;
begin
  if auth.uid() is null then
    raise exception 'Not signed in';
  end if;
  insert into public.households (baby_name, birth_date) values (coalesce(baby_name, ''), birth_date)
  returning * into created;
  insert into public.household_members (household_id, user_id) values (created.id, auth.uid());
  return created;
end;
$$;

create function public.join_household(code text) returns public.households
language plpgsql security definer set search_path = '' as $$
declare
  found public.households;
begin
  if auth.uid() is null then
    raise exception 'Not signed in';
  end if;
  select * into found from public.households where invite_code = upper(trim(code));
  if found.id is null then
    raise exception 'No household has that invite code';
  end if;
  insert into public.household_members (household_id, user_id) values (found.id, auth.uid())
  on conflict do nothing;
  return found;
end;
$$;

revoke execute on function public.create_household(text, date) from public, anon;
revoke execute on function public.join_household(text) from public, anon;
revoke execute on function public.is_household_member(uuid) from public, anon;
grant execute on function public.create_household(text, date) to authenticated;
grant execute on function public.join_household(text) to authenticated;
grant execute on function public.is_household_member(uuid) to authenticated;

-- Live updates: a timer started on one phone shows up on the other.
alter publication supabase_realtime add table public.entries, public.households;
